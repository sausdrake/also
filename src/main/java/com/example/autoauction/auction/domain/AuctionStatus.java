package com.example.autoauction.auction.domain;

public enum AuctionStatus {
    CREATED,             // Создан, ещё не начался
    ACTIVE,              // Торги идут
    WAITING_FOR_PAYMENT, // Победитель определён, продажа ожидает подтверждения (оплата + передача)
    SOLD,                // Продажа подтверждена администратором (оплата и передача проверены)
    SALE_FAILED,         // Продажа не состоялась после определения победителя (детали - в SaleResolution)
    EXPIRED,             // Истёк без ставок
    CANCELLED,           // Отменён администратором

    /**
     * LEGACY ONLY (Slice 1a). Означает исторически: "торги завершились с победителем" - до
     * введения WAITING_FOR_PAYMENT/SOLD-контракта. НЕ означает, что оплата или передача
     * автомобиля были подтверждены - эти факты никогда не фиксировались для записей с этим
     * статусом. Новый код никогда не должен присваивать это значение; сохранён только для
     * совместимости с историческими записями (см. миграцию V31).
     */
    @Deprecated
    COMPLETED
}
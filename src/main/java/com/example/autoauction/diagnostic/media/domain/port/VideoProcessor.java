package com.example.autoauction.diagnostic.media.domain.port;

import java.nio.file.Path;

/**
 * MEDIA-3.4. Application-facing video-processing port. The domain/application
 * layer knows nothing about FFmpeg, subprocesses, or any other engine choice -
 * only this interface and its value types (mirrors how StorageClient hides R2/
 * the AWS SDK). FfmpegVideoProcessor is the sole production adapter; a future
 * engine swap would only touch a new adapter behind this same port.
 */
public interface VideoProcessor {

    /**
     * Extracts metadata and generates a single thumbnail frame from a video
     * already downloaded to local disk. Implementations must write the
     * thumbnail file into videoFile's own parent directory (never elsewhere) -
     * the caller owns exactly one temp directory per processing attempt and
     * deletes it wholesale when done, so anything written outside that
     * directory would never be cleaned up. videoFile and the returned
     * thumbnail path are always server-generated by the caller; this port
     * never accepts or derives a path from client input.
     *
     * Failures (malformed/unreadable video, unsupported content, processing
     * timeout, non-zero engine exit) propagate as an unchecked exception -
     * implementations must not swallow them into a silent/default result.
     */
    ProcessingResult process(Path videoFile, ProcessingLimits limits);

    /**
     * Bounds enforced by the processor before/during extraction - server-side
     * configuration only, never derived from client-declared values.
     * Constructed by the caller (VideoProcessingService) from its own
     * configuration and passed in, so limits are configured in exactly one
     * place, not duplicated between the port's caller and its adapter.
     */
    record ProcessingLimits(
            int maxDurationSeconds,
            int maxWidth,
            int maxHeight,
            int thumbnailMaxWidth,
            int thumbnailMaxHeight) {}

    /** Server-derived (never client-declared) video metadata plus the generated thumbnail's local path. */
    record ProcessingResult(
            int durationSeconds,
            int width,
            int height,
            Path thumbnailFile) {}
}
